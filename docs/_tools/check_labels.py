#!/usr/bin/env python3
"""Check the label contract against a build's ``objects.inv``.

Usage: ``python docs/_tools/check_labels.py <html outdir> [--owner W3] [--write]``

``docs/_tools/label_contract.txt`` lists every label the site must keep (the labels of
0.1 and of the v2 pages, and the PR15b contract labels) and every glossary term
(``term:<name>``), each with the writer whose files own it. The check fails when a listed label is missing from the build's ``std:label``
inventory, or sits on a page outside its owner's files (a label may move between its
owner's pages, never to another writer's). Page-private labels a writer adds are not
listed and not checked. ``--owner`` restricts the check to one writer's labels;
``--write`` regenerates the contract from the build (integrator only).
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
CONTRACT = HERE / "label_contract.txt"

# docname prefixes (or exact docnames) of each writer's files (design section 8.1)
OWNERS = {
    "W1": ("upgrading/",),
    "W2": ("user-guide/generating", "user-guide/curricula", "user-guide/results",
           "tutorials/batch-of-tracks", "tutorials/gate-sequences",
           "tutorials/choosing-a-generator", "tracks-25d", "gates-3d",
           "configuration/tuning"),
    "W3": ("utilities/", "user-guide/rl-auto-reset", "tutorials/cuda-graph-in-a-sim"),
    "W4": ("contributing/writing-a-generator", "contributing/writing-a-gate-generator",
           "contributing/writing-a-stage", "contributing/writing-a-component",
           "contributing/testing-a-plugin", "contributing/packaging-a-plugin",
           "contributing/plugin-abis"),
    "W5": ("reference/", "configuration/reference"),
    "W6": ("how-it-works/", "relaxation/", "generators/", "contributing/rendering-assets",
           "contributing/dev-setup", "related-work/", "appendix/"),
    "W7": ("getting-started/",),
    "integrator": ("index",),
}


def owner_of(docname: str) -> str | None:
    for owner, prefixes in OWNERS.items():
        for p in prefixes:
            if docname == p or (p.endswith("/") and docname.startswith(p)):
                return owner
    return None


def labels_of(outdir: Path) -> dict[str, str]:
    from sphinx.util.inventory import InventoryFile
    with open(outdir / "objects.inv", "rb") as f:
        inv = InventoryFile.load(f, "", lambda base, uri: uri)
    out = {}
    items = inv.data.items() if hasattr(inv, "data") else inv.items()
    for typ, entries in items:
        if typ not in ("std:label", "std:term"):
            continue
        for name, entry in entries.items():
            uri = entry.uri if hasattr(entry, "uri") else entry[2]
            key = name if typ == "std:label" else f"term:{name.lower()}"
            out[key] = uri.split("#", 1)[0].removesuffix(".html")
    return out


def read_contract() -> list[tuple[str, str]]:
    out = []
    for line in CONTRACT.read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            label, owner = line.split("\t")[:2]
            out.append((label.strip(), owner.strip()))
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("outdir", type=Path)
    ap.add_argument("--owner")
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args(argv)
    built = labels_of(a.outdir)
    if a.write:
        lines = ["# label<TAB>owner<TAB>page at the time of writing. Generated by "
                 "check_labels.py --write;", "# see the module docstring. Writers never edit "
                 "this file."]
        for name, doc in sorted(built.items()):
            if name in ("genindex", "modindex", "py-modindex", "search"):
                continue
            lines.append(f"{name}\t{owner_of(doc) or '?'}\t{doc}")
        CONTRACT.write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(f"wrote {len(lines) - 2} labels to {CONTRACT}")
        return 0
    problems = []
    checked = 0
    for label, owner in read_contract():
        if a.owner and owner != a.owner:
            continue
        checked += 1
        doc = built.get(label)
        if doc is None:
            problems.append(f"missing label {label!r} (owner {owner})")
        elif owner_of(doc) != owner:
            problems.append(f"label {label!r} (owner {owner}) is on {doc}, "
                            f"a page of {owner_of(doc)}")
    for p in problems:
        print(p)
    print(f"{checked} contract labels checked, {len(problems)} problems")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
